#!/usr/bin/env python3
"""Patch a real app manifest, or check a merged/bundletool-dumped manifest.
No package IDs, ad IDs or credentials are generated by this tool.
"""
import argparse, pathlib, sys, xml.etree.ElementTree as ET, shutil
A='http://schemas.android.com/apk/res/android'; T='http://schemas.android.com/tools'
ET.register_namespace('android',A); ET.register_namespace('tools',T)
def a(s): return '{'+A+'}'+s
FEATURES=['android.hardware.screen.portrait','android.hardware.screen.landscape']
PERMS=['android.permission.INTERNET','android.permission.ACCESS_NETWORK_STATE','com.google.android.gms.permission.AD_ID']

def patch(root):
    for name in FEATURES:
        nodes=[e for e in root.findall('uses-feature') if e.get(a('name'))==name]
        node=nodes[0] if nodes else ET.SubElement(root,'uses-feature',{a('name'):name})
        node.set(a('required'),'false')
        for extra in nodes[1:]: root.remove(extra)
        # Remove a contradictory merger removal marker if present.
        if node.get('{'+T+'}node')=='remove': del node.attrib['{'+T+'}node']
    for name in PERMS:
        nodes=[e for e in root.findall('uses-permission') if e.get(a('name'))==name]
        node=nodes[0] if nodes else ET.SubElement(root,'uses-permission',{a('name'):name})
        for extra in nodes[1:]:root.remove(extra)
        if node.get('{'+T+'}node')=='remove':del node.attrib['{'+T+'}node']
        # AD_ID must not be capped at an OS version below our target.
        if name.endswith('.AD_ID'):node.attrib.pop(a('maxSdkVersion'),None)
    # Keep existing app identity and existing activity orientation. Move declarations before application.
    app=root.find('application')
    if app is not None:
        for e in list(root):
            if e.tag in ('uses-feature','uses-permission') and list(root).index(e)>list(root).index(app):
                root.remove(e);root.insert(list(root).index(app),e)
        app.set(a('appCategory'),'game')

def check(root):
    errors=[];warnings=[]
    for name in FEATURES:
        nodes=[e for e in root.findall('uses-feature') if e.get(a('name'))==name]
        if not nodes or any(e.get(a('required'))!='false' for e in nodes):errors.append(name+' must explicitly be optional')
    for name in PERMS:
        if not any(e.get(a('name'))==name and e.get(a('maxSdkVersion')) is None for e in root.findall('uses-permission')):errors.append('Missing unrestricted '+name)
    sdk=root.find('uses-sdk');target=sdk.get(a('targetSdkVersion'),'') if sdk is not None else ''
    if not target.isdecimal() or int(target)<36:errors.append('Final merged manifest must show numeric targetSdkVersion >= 36')
    app=root.find('application')
    if app is None:errors.append('Missing application element');return errors,warnings
    if app.get(a('debuggable'))=='true':errors.append('Release manifest is debuggable')
    if app.get(a('resizeableActivity'))=='false':errors.append('Application must allow resizing')
    for activity in app.findall('activity'):
        name=activity.get(a('name'),'')
        if activity.get(a('resizeableActivity'))=='false':errors.append(name+' disallows resizing')
        if activity.get(a('screenOrientation'),'unspecified') not in ('unspecified','fullSensor','fullUser','user','sensor'):errors.append(name+' restricts orientation')
        if activity.get(a('maxAspectRatio')) or activity.get(a('minAspectRatio')):errors.append(name+' restricts aspect ratio')
    if app.get(a('appCategory'))!='game':warnings.append('Set appCategory=game for this game')
    ids=[e.get(a('value'),'') for e in app.findall('meta-data') if e.get(a('name'))=='com.google.android.gms.ads.APPLICATION_ID']
    import re
    if len(ids)!=1 or not re.fullmatch(r'ca-app-pub-\d{16}~\d{10}',ids[0]) or ids[0].startswith('ca-app-pub-3940256099942544~'):
        errors.append('Set the real AdMob application ID (not sample ID or placeholder) in final manifest')
    for e in root.findall('uses-feature'):
        if e.get(a('required'),'true')!='false':warnings.append('Review required feature: '+str(e.get(a('name'),e.get(a('glEsVersion'),'unknown'))))
    return errors,warnings

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('mode',choices=['patch','check']);p.add_argument('manifest',type=pathlib.Path);q=p.parse_args()
    tree=ET.parse(q.manifest);root=tree.getroot()
    if root.tag!='manifest':p.error('Not a manifest XML')
    if q.mode=='patch':
        backup=q.manifest.with_name(q.manifest.name+'.preflight.bak')
        if not backup.exists():shutil.copy2(q.manifest,backup)
        patch(root);ET.indent(tree,space='    ');tree.write(q.manifest,encoding='utf-8',xml_declaration=True)
        print('Patched source manifest; backup:',backup);print('Final merged manifest check still required.');return 0
    errors,warnings=check(root)
    for w in warnings:print('REVIEW:',w)
    for e in errors:print('FAIL:',e)
    print('PASS: targeted manifest checks only' if not errors else 'FAIL: manifest not ready')
    return bool(errors)
if __name__=='__main__':sys.exit(main())
